#!/usr/bin/env bash
# One-time migration ONLY: original 1.2.9 -> new VM with clean 1.4 already installed.
# Copies the original Gitea DB/repositories/identities and migrates local LFS to private R2.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
[[ $EUID == 0 ]] || die 'Use sudo on the NEW SWVAULT 1.4 VM.'
[[ -r /dev/tty ]] || die 'Interactive terminal required.'
[[ $# == 2 && "$1" == /* && "$2" == /* ]] || die 'Usage: sudo ./import-129-fresh-vm.sh /path/old-129-final.tar.gz /separate-disk/import-safety-dir (required even if nightly backups are disabled)'
archive="$1"; backup="$2"
[[ -s "$archive" ]] || die 'Missing 1.2.9 export archive.'
[[ "$(env_get CF_DEPLOYMENT)" == cloudflare ]] || die 'Complete the fresh 1.4 setup.sh first.'
[[ ! -f "$DATA_DIR/r2-transfer/migration-ready.json" ]] || die 'Cutover is already armed. Refusing import.'
[[ -d "$DATA_DIR/gitea" ]] || die 'New VM Gitea data missing.'
mkdir -p "$backup"
[[ "$(df -P "$backup" | tail -1 | awk '{print $1}')" != "$(df -P "$DATA_DIR" | tail -1 | awk '{print $1}')" ]] || die 'Full-history import rollback/staging must be on an independent disk even when nightly backups are disabled.'
[[ "$archive" != "$SWVAULT_DIR"/* ]] || die 'Export archive must be outside deployment directory.'
umask 077
# Never extract a 100+GB archive in /tmp; use the independent backup filesystem.
stage="$(mktemp -d "$backup/.swvault-import-stage.XXXXXXXX")"
rollback_ready=no
import_changes_started=no
services_stopped=no
restore=''
cleanup() {
  local rc=$?
  trap - EXIT
  if (( rc != 0 )) && [[ "$rollback_ready" == yes && "$import_changes_started" == yes && -s "$restore/fresh-vm-state.tar.gz" ]]; then
    warn 'Import failed. Restoring the NEW VM pre-import snapshot. The original VM was never modified.'
    compose stop proxy r2-transfer invites gitea >/dev/null 2>&1 || true
    rm -rf "$DATA_DIR/gitea" "$DATA_DIR/invites"
    tar -xzf "$restore/fresh-vm-state.tar.gz" -C "$SWVAULT_DIR" || warn 'Automatic restore failed; restore the pre-import snapshot manually.'
    compose up -d --build --remove-orphans >/dev/null 2>&1 || warn 'Manual service restart may be needed.'
  fi
  if (( rc != 0 )) && [[ "$services_stopped" == yes && "$import_changes_started" == no ]]; then
    compose up -d --build --remove-orphans >/dev/null 2>&1 || true
  fi
  systemctl enable --now swvault-watchdog.timer >/dev/null 2>&1 || true
  if [[ "$(env_get BACKUPS_ENABLED)" != no ]]; then
    systemctl enable --now swvault-backup.timer >/dev/null 2>&1 || true
  else
    systemctl disable --now swvault-backup.timer >/dev/null 2>&1 || true
  fi
  rm -rf "$stage"
  exit "$rc"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
# Only import an archive generated by the old VM's export script.
python3 - "$archive" "$backup" <<'PY'
import sys, tarfile, shutil
bytes_needed = 0
with tarfile.open(sys.argv[1], 'r:gz') as t:
    for info in t:
        bytes_needed += info.size
        n = info.name
        if n.startswith('/') or '..' in n.split('/') or not (n == '.env' or n == 'team.json' or n.startswith('data/gitea/') or n == 'data/gitea' or n.startswith('data/invites/') or n == 'data/invites' or n == 'data/admin-token' or n in ('team-icon.png', 'invites/web/logo.svg', 'invites/web/logo-light.svg')):
            raise SystemExit('Unexpected archive member: ' + n)
        if info.issym() or info.islnk() or info.isdev():
            raise SystemExit('Link/device in migration archive is not allowed: ' + n)
free_bytes = shutil.disk_usage(sys.argv[2]).free
if free_bytes < bytes_needed + 4 * 1024**3:
    raise SystemExit(f'Insufficient independent backup disk free space: need at least {bytes_needed / 1024**3:.1f} GiB plus 4 GiB margin for staging')
PY
tar -xzf "$archive" -C "$stage"
[[ -f "$stage/.env" && -f "$stage/team.json" && -d "$stage/data/gitea" ]] || die 'Export is incomplete.'
source_kb="$(du -sk "$stage/data/gitea" | awk '{print $1}')"
root_free_kb="$(df -Pk "$DATA_DIR" | awk 'NR==2 {print $4}')"
(( root_free_kb > source_kb + 4194304 )) || die 'New VM data disk has insufficient free space for imported Gitea/LFS plus 4 GiB.' 
old_env() { grep -E "^$1=" "$stage/.env" | tail -1 | cut -d= -f2- || true; }
old_url="$(jq -r '.vaultUrl // empty' "$stage/team.json")"
[[ "$old_url" == https://*.ts.net/* ]] || die 'Old team.json does not contain a Tailscale HTTPS repository URL.'
old_org="$(old_env ORG)"; old_repo="$(old_env REPO)"; old_admin="$(old_env ADMIN_USER)"
for key in ORG REPO ADMIN_USER; do
  case "$key" in ORG) old="$old_org";; REPO) old="$old_repo";; ADMIN_USER) old="$old_admin";; esac
  [[ -n "$old" && "$old" == "$(env_get "$key")" ]] || die "$key differs between 1.2.9 and the new VM. Reinstall a FRESH 1.4 VM with the original value; this import cannot rewrite vault history."
done
oldcount="$(find "$stage/data/gitea/git/lfs" -type f 2>/dev/null | wc -l)"
printf '\nSource repository: %s\nPrivate R2 bucket: %s\nHistorical local LFS files: %s\n' "$old_url" "$(env_get R2_BUCKET)" "$oldcount"
echo 'No existing production VM will be modified by this import.'
read -r -p 'Type IMPORT_129 to replace the NEW VM test database with this snapshot: ' confirm </dev/tty
[[ "$confirm" == IMPORT_129 ]] || die 'Cancelled without changes.'
stamp="$(date -u +%Y%m%dT%H%M%SZ)"
restore="$backup/swvault-14-before-129-import-$stamp"
mkdir -p "$restore"
# Stop 1.4 services and watchdogs to avoid mixed old/new data.
systemctl stop swvault-watchdog.timer swvault-watchdog.service swvault-backup.timer swvault-backup.service >/dev/null 2>&1 || true
compose stop proxy r2-transfer invites gitea
services_stopped=yes
tar -czf "$restore/fresh-vm-state.tar.gz" -C "$SWVAULT_DIR" .env team.json data/gitea data/invites data/admin-token
[[ -s "$restore/fresh-vm-state.tar.gz" ]] || die 'Failed to back up new VM state.'
rollback_ready=yes
import_changes_started=yes
# Copy original Gitea data to the newly provisioned VM, retaining the source archive intact.
rm -rf "$DATA_DIR/gitea"
mkdir -p "$DATA_DIR/gitea"
cp -a "$stage/data/gitea/." "$DATA_DIR/gitea/"
chown -R 1000:1000 "$DATA_DIR/gitea"
if [[ -d "$stage/data/invites" ]]; then
  rm -rf "$DATA_DIR/invites"; mkdir -p "$DATA_DIR/invites"
  cp -a "$stage/data/invites/." "$DATA_DIR/invites/"
fi
if [[ -f "$stage/data/admin-token" ]]; then
  cp -p "$stage/data/admin-token" "$ADMIN_TOKEN_FILE"
  chown 0:1000 "$ADMIN_TOKEN_FILE"; chmod 640 "$ADMIN_TOKEN_FILE"
fi
# Preserving Gitea SECRET_KEY, INTERNAL_TOKEN and JWT secrets keeps existing
# user tokens and other encrypted metadata usable after DB import.
for key in GITEA_SECRET_KEY GITEA_INTERNAL_TOKEN GITEA_LFS_JWT_SECRET GITEA_OAUTH_JWT_SECRET; do
  value="$(old_env "$key")"
  [[ -n "$value" ]] || die "Original 1.2.9 .env lacks $key; manual compatibility review required."
  env_set "$key" "$value"
done
# Transfer team policy and mail settings, but NOT the old Tailscale keys,
# old URL, obsolete watchdog or auto-update configuration.
for key in TEAM_NAME LOCAL_ROOT SW_VERSION EMAIL_DOMAINS SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASSWORD SMTP_FROM; do
  value="$(old_env "$key")"
  [[ -z "$value" ]] || env_set "$key" "$value"
done
for custom in team-icon.png invites/web/logo.svg invites/web/logo-light.svg; do
  if [[ -f "$stage/$custom" ]]; then
    mkdir -p "$SWVAULT_DIR/$(dirname "$custom")"
    cp -p "$stage/$custom" "$SWVAULT_DIR/$custom"
  fi
done
env_set PREVIOUS_VAULT_URL "$old_url"
# CLI must READ local source storage (the imported 1.2.9 tree); new Gitea
# will use R2 after migration. Do not delete local LFS objects.
echo 'Migrating DB-referenced historical LFS objects from new VM local disk into R2...'
compose up -d cloudflared
AWS_ACCESS_KEY_ID="$(env_get R2_ACCESS_KEY_ID)" AWS_SECRET_ACCESS_KEY="$(env_get R2_SECRET_ACCESS_KEY)" \
  compose run --rm --no-deps -u git -e GITEA__lfs__STORAGE_TYPE=local \
    -e AWS_ACCESS_KEY_ID -e AWS_SECRET_ACCESS_KEY gitea \
  gitea migrate-storage --type lfs --storage minio \
  --minio-endpoint "$(env_get R2_ACCOUNT_ID).r2.cloudflarestorage.com" \
  --minio-bucket "$(env_get R2_BUCKET)" --minio-location auto --minio-base-path lfs/ \
  --minio-use-ssl --minio-checksum-algorithm md5 --minio-bucket-lookup-type path
# Old LFS directory itself is preserved on the new VM as cold/archive storage.
compose up -d --build --remove-orphans
wait_gitea 300
write_team_json
chmod 644 "$TEAM_FILE"
echo 'Checking signed direct R2 GET from restored Gitea metadata...'
"$SWVAULT_DIR/verify-r2-direct.sh"
[[ -n "$(env_get PREVIOUS_VAULT_URL)" ]] || die 'Old URL missing; do not arm cutover.'
printf '\nImported 1.2.9 users, Git history, locks, invites and LFS.\nOld server remains frozen. New URL: %s\n' "$(vault_url)"
printf 'ROLLBACK COPY OF EMPTY 1.4 VM: %s\n' "$restore/fresh-vm-state.tar.gz"
echo 'Run the real Windows 1.4 client pilot BEFORE arm-129-cutover.sh.'
